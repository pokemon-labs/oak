// Showdown's Gen 1 display names for libpkmn's species, moves and types, in
// libpkmn's order (cpp/include/libpkmn/data/strings.h's ID arrays), as the
// text protocol spells them. Needs a built Showdown (SHOWDOWN, default
// ~/pokemon-showdown).
//
//   node codegen/names.cjs > src/names.hpp
const path = require('path');
const fs = require('fs');
const os = require('os');
const showdown = process.env.SHOWDOWN || path.join(os.homedir(), 'pokemon-showdown');
const {Dex} = require(path.join(showdown, 'dist/sim'));
const dex = Dex.mod('gen1');

const src = fs.readFileSync(path.join(__dirname, '../../cpp/include/libpkmn/data/strings.h'), 'utf8');
const ids = array => {
  const m = src.match(new RegExp(array + '[^{]*\\{\\{?([^}]*)\\}'));
  return [...m[1].matchAll(/"([^"]*)"/g)].map(x => x[1]);
};
const names = (table, list) => list.map((id, i) => {
  if (i === 0 && id === 'None') return '';
  const x = table.get(id);
  if (!x.exists) throw new Error(`unknown ${id}`);
  return x.name;
});
const species = names(dex.species, ids('SPECIES_CHAR_ARRAY'));
const moves = names(dex.moves, ids('MOVE_CHAR_ARRAY'));
const types = ids('TYPE_CHAR_ARRAY').map(t => dex.types.get(t).name);
const list = xs => xs.map(x => `    ${JSON.stringify(x)},`).join('\n');
console.log(`// Generated by codegen/names.cjs: Showdown's Gen 1 display names, by
// libpkmn's IDs (index 0 is None, an empty name).

#pragma once

#include <array>
#include <string_view>

namespace ataraxos::names {

inline constexpr std::array<std::string_view, ${species.length}> SPECIES = {
${list(species)}
};

inline constexpr std::array<std::string_view, ${moves.length}> MOVES = {
${list(moves)}
};

inline constexpr std::array<std::string_view, ${types.length}> TYPES = {
${list(types)}
};

} // namespace ataraxos::names`);
